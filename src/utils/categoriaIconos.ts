const normalizarCategoria = (valor?: string | null): string => {
  return (valor || "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
};

export const obtenerIconoCategoria = (nombre: string): string => {
  const iconoDirecto = categoriaIconos[nombre];

  if (iconoDirecto) return iconoDirecto;

  const nombreNormalizado = normalizarCategoria(nombre);

  const categoriaEncontrada = Object.entries(categoriaIconos).find(
    ([categoria]) => normalizarCategoria(categoria) === nombreNormalizado,
  );

  return categoriaEncontrada?.[1] || "📦";
};
